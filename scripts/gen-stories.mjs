// Generate Storybook stories from the repo's single sources. Re-run after adding
// components or sections:  node scripts/gen-stories.mjs
//  - Components (js/components-data.js): one Docs + Playground per component.
//  - Sections   (js/sections.js):        per BUILT version, a Documentation + Playground
//    leaf grouped under its family (Sections/<Family>/<Version> - Documentation|Playground).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataSrc = fs.readFileSync(path.join(root, 'js/components-data.js'), 'utf8');
const comps = eval('(' + dataSrc.split('window.ERAIKI_COMPONENTS =')[1].trim().replace(/;\s*$/, '') + ')');

const outDir = path.join(root, 'storybook/stories/components');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const esc = (s) => String(s).replace(/'/g, "\\'");
for (const c of comps) {
  const file = c.name.replace(/[^A-Za-z0-9]+/g, '') + '.stories.js';
  const s = esc(c.slug);
  const content = "// AUTO-GENERATED by scripts/gen-stories.mjs — do not hand-edit.\n"
    + "// Connected to the repo's single sources:\n"
    + "//  - Docs page: written documentation from js/components-data.js\n"
    + "//  - Playground: prop-driven live emulator from js/playgrounds.js\n"
    + "import { playgroundArgTypes, playgroundArgs, playgroundRender, docMarkdown } from '../_component.js';\n"
    + "import { DocsPage } from '../_docspage.js';\n\n"
    + `export default {\n`
    + `  title: 'Components/${esc(c.name)}',\n`
    + `  tags: ['autodocs'],\n`
    + `  parameters: { layout: 'fullscreen', docs: { page: DocsPage, description: { component: docMarkdown('${s}') } } },\n`
    + `};\n\n`
    + `export const Playground = { name: 'Playground', argTypes: playgroundArgTypes('${s}'), args: playgroundArgs('${s}'), render: (a) => playgroundRender('${s}', a) };\n`;
  fs.writeFileSync(path.join(outDir, file), content);
}
console.log('generated', comps.length, 'component stories in', path.relative(root, outDir));

// ---- Sections: one story per BUILT version (has a builder in SECTION_BUILD) ----
globalThis.window = globalThis; // so js/sections.js (bare `window`) loads under Node
createRequire(import.meta.url)(path.join(root, 'js/sections.js'));
const SECTIONS = globalThis.ERAIKI_SECTIONS || [];
const BUILD = globalThis.ERAIKI_SECTIONS_BUILD || {};

const secDir = path.join(root, 'storybook/stories/sections');
fs.rmSync(secDir, { recursive: true, force: true });
fs.mkdirSync(secDir, { recursive: true });

let secCount = 0;
for (const sec of SECTIONS) {
  for (const v of sec.versions || []) {
    if (!BUILD[v.slug]) continue; // only built versions
    const s = esc(v.slug);
    const base = v.name.replace(/[^A-Za-z0-9]+/g, '');
    const group = `Sections/${esc(sec.name)}`;
    // Playground: one story whose name matches the title's last segment, so Storybook
    // hoists it to a single sidebar leaf ("Explanation Banner Card - Playground").
    const playground = `${esc(v.name)} - Playground`;
    const story = "// AUTO-GENERATED by scripts/gen-stories.mjs — do not hand-edit.\n"
      + "// Connected to the repo's single source (js/sections.js): live markup.\n"
      + "import { sectionRender, sectionControls } from '../_section.js';\n\n"
      + `export default {\n`
      + `  title: '${group}/${playground}',\n`
      + `  parameters: { layout: 'fullscreen' },\n`
      + `};\n\n`
      + `// Versions with layout options (Figma "Options") get an Option control; the rest none.\n`
      + `export const Playground = { name: '${playground}', ...sectionControls('${s}'), render: (args) => sectionRender('${s}', args.option) };\n`;
    fs.writeFileSync(path.join(secDir, base + '.stories.js'), story);
    // Documentation: an unattached docs page, a sibling leaf of the Playground. Same
    // layout as the component Docs pages: title, the live section, then the written
    // docs (short, context, keywords, when to use / when not to use).
    // Options (when the version has them) sit between the summary and the long docs,
    // as in the Figma doc frame: Overview → Options → Description.
    const body = `# ${v.name}\n\n`
      + `<Canvas of={Stories.Playground} sourceState="none" />\n\n`
      + `<Markdown>{sectionDoc('${s}', 'short')}</Markdown>\n\n`
      + `<SectionOptions slug="${s}" />\n\n`
      + `<Markdown>{sectionDoc('${s}', 'body')}</Markdown>\n`;
    const docs = "{/* AUTO-GENERATED by scripts/gen-stories.mjs — do not hand-edit. */}\n"
      + "{/* Connected to the repo's single source (js/sections.js): live markup + written docs. */}\n"
      + "import { Meta, Canvas, Markdown } from '@storybook/addon-docs/blocks';\n"
      + `import * as Stories from './${base}.stories.js';\n`
      + "import { sectionDoc, SectionOptions } from '../_section.js';\n\n"
      + `<Meta title="${group.replace(/"/g, '&quot;')}/${v.name.replace(/"/g, '&quot;')} - Documentation" />\n\n`
      + body;
    fs.writeFileSync(path.join(secDir, base + '.mdx'), docs);
    secCount += 1;
  }
}
console.log('generated', secCount, 'section docs + playgrounds in', path.relative(root, secDir));
